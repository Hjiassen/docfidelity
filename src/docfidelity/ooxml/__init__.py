"""OOXML 基础设施 —— 样式保真承诺的技术边界（DD-4）。

铁律
----
**一切写入都是"在原件深拷贝上做最小必要改动"，任何"按契约重建 XML"的实现都是缺陷。**
样式由模板契约指明**位置**，但渲染材料一律取自原件：本模块因此从不自行拼装
``w:pPr`` / ``w:tblPr`` 之类会决定版式的 XML，只做定位、替换与必要的最小插入。

子模块
------
doc        命名空间、标签构造与段落级读写原语
package    包与部件、关系解析、惰性加载与原子写（读用 ``read_tree``，写用 ``tree``）
styles     样式读取 / 克隆 / ID 重映射（**含 ``w:tblStyle``**）/ 直设格式检测
numbering  编号读取、标题绑定、等价定义合并、双重编号检测
geometry   版心推导、只缩不放、列宽归一（纯函数，无 I/O）
pictures   ``wp:extent`` 读写、内联放置、图注绑定
fields     目录重建、域刷新与 Office 降级
normalize  易变标识归一化：指纹 / 版本 diff / golden 比对共用的唯一实现

.. note::
   本模块只允许依赖 ``contracts`` 与 ``platform``（DD-2.2）。``compose`` 与
   ``server`` 被明文禁止 import 本包，由 ``.importlinter`` 强制。
"""

